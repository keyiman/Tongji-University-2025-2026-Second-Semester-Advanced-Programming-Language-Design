/***************************************************************************
  函数名称：tj_strlen
  功    能：求字符串str的长度
  输入参数：const char str[]
  返 回 值：字符串长度
  说    明：
***************************************************************************/
int tj_strlen(const char str[])
{
    /* 注意：函数内不允许定义任何形式的数组（包括静态数组） */
    int len = 0;
    int i = 0;
    while (str[i] != '\0')
    {
        i++;
        len++;
    }
    return len; //return值可根据需要修改
}

